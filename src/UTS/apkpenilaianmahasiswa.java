    private int getSksDariCombo() {
        String item = matkulcb.getSelectedItem().toString();
        return item.contains("(3 SKS)") ? 3 : 2;
    }

    private void updateSks() {
        sksTxt.setText(String.valueOf(getSksDariCombo()));
    }

    private int jumlahPertemuan(int sks) {
        return (sks == 3) ? 21 : 14;
    }

    private boolean proses() {
        if (presensiTxt.getText().trim().isEmpty() || tugasTxt.getText().trim().isEmpty()
                || utsTxt.getText().trim().isEmpty() || uasTxt.getText().trim().isEmpty()) {
            javax.swing.JOptionPane.showMessageDialog(this,
                    "Presensi, Tugas, UTS, dan UAS harus diisi!",
                    "Peringatan", javax.swing.JOptionPane.WARNING_MESSAGE);
            return false;
        }

        double presensi, tugas, uts, uas;
        try {
            presensi = Double.parseDouble(presensiTxt.getText().trim());
            tugas = Double.parseDouble(tugasTxt.getText().trim());
            uts = Double.parseDouble(utsTxt.getText().trim());
            uas = Double.parseDouble(uasTxt.getText().trim());
        } catch (NumberFormatException ex) {
            javax.swing.JOptionPane.showMessageDialog(this,
                    "Nilai harus berupa angka!",
                    "Kesalahan Input", javax.swing.JOptionPane.ERROR_MESSAGE);
            return false;
        }

        int sks = getSksDariCombo();
        int pertemuan = jumlahPertemuan(sks);

        if (presensi < 0 || presensi > pertemuan) {
            javax.swing.JOptionPane.showMessageDialog(this,
                    "Presensi tidak valid!\nJumlah pertemuan " + sks + " SKS adalah "
                    + pertemuan + ", presensi tidak boleh melebihi " + pertemuan + ".",
                    "Validasi Presensi", javax.swing.JOptionPane.ERROR_MESSAGE);
            presensiTxt.requestFocus();
            return false;
        }
        if (tugas < 0 || tugas > 100 || uts < 0 || uts > 100 || uas < 0 || uas > 100) {
            javax.swing.JOptionPane.showMessageDialog(this,
                    "Nilai Tugas, UTS, dan UAS harus antara 0 - 100!",
                    "Validasi Nilai", javax.swing.JOptionPane.ERROR_MESSAGE);
            return false;
        }

        double persenHadir = (presensi / pertemuan) * 100;
        double nilaiAkhir = (persenHadir * 0.1) + (tugas * 0.2) + (uts * 0.3) + (uas * 0.4);

        String grade;
        if (persenHadir < 50) {
            grade = "E";
        } else if (persenHadir < 75) {
            grade = "D";
        } else if (nilaiAkhir > 80) {
            grade = "A";
        } else if (nilaiAkhir > 60) {
            grade = "B";
        } else if (nilaiAkhir > 40) {
            grade = "C";
        } else {
            grade = "E";
        }

        nilaiakhirTxt.setText(String.format("%.2f", nilaiAkhir));
        gradeTxt.setText(grade);
        return true;
    }

    private void addData() {
        if (nimTxt.getText().trim().isEmpty() || namaTxt.getText().trim().isEmpty()) {
            javax.swing.JOptionPane.showMessageDialog(this,
                    "NIM dan Nama harus diisi!",
                    "Peringatan", javax.swing.JOptionPane.WARNING_MESSAGE);
            return;
        }
        if (!proses()) {
            return;
        }

        String jk = lakirb.isSelected() ? "LAKI-LAKI" : "PEREMPUAN";
        String baris = nimTxt.getText().trim() + " | " + namaTxt.getText().trim()
                + " | " + jk
                + " | Matkul : " + matkulcb.getSelectedItem().toString().replaceAll("\\(.*\\)", "").trim()                + " | SKS : " + sksTxt.getText()
                + " | Absensi : " + presensiTxt.getText().trim()
                + " | Tugas : " + tugasTxt.getText().trim()
                + " | UTS : " + utsTxt.getText().trim()
                + " | UAS : " + uasTxt.getText().trim()
                + " | Nilai Akhir : " + nilaiakhirTxt.getText()
                + " | Grade : " + gradeTxt.getText();

        logTxt.append(baris + "\n");
    }

